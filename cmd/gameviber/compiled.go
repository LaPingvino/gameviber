package main

// Exported desktop games with their Go compiled in (item 13, step 3b): when a
// game has .go events or scripts and Go is installed, the export builds a
// player of its own — the game's Go turned into packages (golang.Generate)
// registered in golang.Compiled, and a main calling player.Main — instead of
// shipping the prebuilt player that interprets them. Anything in the way (no
// Go, a system this machine can't build for, no GameViber source to build
// against) → the prebuilt player, interpreted, as before, with a note why.

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"runtime/debug"
	"strings"

	"github.com/LaPingvino/gameviber/import/gmfile"
	"github.com/LaPingvino/gameviber/lang/golang"
)

const gameviberModule = "github.com/LaPingvino/gameviber"

// goFiles are a game's Go events and scripts, named as the loader names them.
func goFiles(p *gmfile.Project) []golang.GenFile {
	var fs []golang.GenFile
	for _, o := range p.Objects {
		if o == nil {
			continue
		}
		for _, ev := range o.Events {
			if ev.Lang != ".go" {
				continue
			}
			if src, ok := ev.Source(); ok {
				fs = append(fs, golang.GenFile{Path: "objects/" + o.Name + "/" + p.EventFile(ev), Src: src})
			}
		}
	}
	for _, sc := range p.Scripts {
		if sc != nil && sc.Lang == ".go" {
			fs = append(fs, golang.GenFile{Path: "scripts/" + sc.Name + ".go", Src: sc.Code, Script: true})
		}
	}
	return fs
}

// canCompileFor: this machine builds windows and the browser (js/wasm)
// without cgo, and its own system with it (Ebitengine needs cgo on Linux;
// macOS needs Apple's tools).
func canCompileFor(goos, goarch string) bool {
	return goos == "windows" || goos == "js" || (goos == runtime.GOOS && goarch == runtime.GOARCH)
}

// gameviberSource says how the build finds GameViber itself: a local checkout
// (GAMEVIBER_SRC), else the version or commit this program was built from.
func gameviberSource() (dir, version string, err error) {
	if d := os.Getenv("GAMEVIBER_SRC"); d != "" {
		return d, "", nil
	}
	bi, ok := debug.ReadBuildInfo()
	if !ok {
		return "", "", errors.New("no build information")
	}
	if v := bi.Main.Version; v != "" && v != "(devel)" {
		return "", v, nil
	}
	rev, dirty := "", false
	for _, s := range bi.Settings {
		switch s.Key {
		case "vcs.revision":
			rev = s.Value
		case "vcs.modified":
			dirty = s.Value == "true"
		}
	}
	if rev == "" || dirty {
		return "", "", errors.New("built from changed sources: set GAMEVIBER_SRC to the checkout")
	}
	return "", rev, nil
}

// compiledPlayer builds a player with the game's Go compiled in.
func compiledPlayer(files []golang.GenFile, goos, goarch string) ([]byte, error) {
	goCmd, err := exec.LookPath("go")
	if err != nil {
		return nil, errors.New("Go is not installed")
	}
	if !canCompileFor(goos, goarch) {
		return nil, fmt.Errorf("this machine can't build for %s/%s", goos, goarch)
	}
	srcDir, version, err := gameviberSource()
	if err != nil {
		return nil, err
	}
	tmp, err := os.MkdirTemp("", "gameviber-build-")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tmp)
	srcs, err := golang.Generate(files, "main", "gvgame")
	if err != nil {
		return nil, err
	}
	srcs["main.go"] = []byte("// Code generated by gameviber export; DO NOT EDIT.\n\npackage main\n\nimport (\n\t\"fmt\"\n\t\"os\"\n\n\t\"" + gameviberModule + "/player\"\n)\n\nfunc main() {\n\tif err := player.Main(os.Args[1:]); err != nil {\n\t\tfmt.Fprintln(os.Stderr, err)\n\t\tos.Exit(1)\n\t}\n}\n")
	srcs["go.mod"] = []byte("module gvgame\n\ngo " + goVersion() + "\n")
	for rel, b := range srcs {
		p := filepath.Join(tmp, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			return nil, err
		}
		if err := os.WriteFile(p, b, 0o644); err != nil {
			return nil, err
		}
	}
	run := func(env []string, args ...string) error {
		c := exec.Command(goCmd, args...)
		c.Dir, c.Env = tmp, append(os.Environ(), env...)
		var out bytes.Buffer
		c.Stdout, c.Stderr = &out, &out
		if err := c.Run(); err != nil {
			return fmt.Errorf("go %s: %v\n%s", args[0], err, strings.TrimSpace(out.String()))
		}
		return nil
	}
	if srcDir != "" {
		abs, _ := filepath.Abs(srcDir)
		if err := run(nil, "mod", "edit", "-require="+gameviberModule+"@v0.0.0", "-replace="+gameviberModule+"="+abs); err != nil {
			return nil, err
		}
	} else if err := run(nil, "get", gameviberModule+"@"+version); err != nil {
		return nil, err
	}
	if err := run(nil, "mod", "tidy"); err != nil {
		return nil, err
	}
	env := []string{"GOOS=" + goos, "GOARCH=" + goarch}
	if goos != runtime.GOOS {
		env = append(env, "CGO_ENABLED=0")
	}
	ld := "-ldflags=-s -w"
	if goos == "windows" {
		ld += " -H=windowsgui" // a game: no console window beside it
	}
	if err := run(env, "build", "-trimpath", ld, "-o", "game.bin", "."); err != nil {
		return nil, err
	}
	return os.ReadFile(filepath.Join(tmp, "game.bin"))
}

// goVersion is this toolchain's language version for go.mod ("1.27.3"; a
// toolchain may add more: "go1.27.3-X:nodwarf5").
func goVersion() string {
	v := strings.TrimPrefix(runtime.Version(), "go")
	if i := strings.IndexFunc(v, func(r rune) bool { return r != '.' && (r < '0' || r > '9') }); i >= 0 {
		v = v[:i]
	}
	return v
}
