package main

import (
	"fmt"
	"io"
	"os"
	"sort"
	"strings"

	"github.com/LaPingvino/gameviber/gml"
	"github.com/LaPingvino/gameviber/runner"
)

// writeReference writes what GameViber understands — for people and agents
// writing GML for it (docs/reference.md is this, generated).
func writeReference(w io.Writer) {
	g := &runner.Game{}
	groups := g.FuncGroups()
	sorted := func(m map[string]bool) []string {
		var out []string
		for k := range m {
			out = append(out, k)
		}
		sort.Strings(out)
		return out
	}
	fmt.Fprint(w, `# GameViber reference

Generated by `+"`gameviber reference`"+` — what GameViber's GML understands today. GameMaker 5.3's language:
statements may end with ; or not, then / do are optional, begin … end are { }, := assigns, = in an expression
compares, and / or / xor / not / div / mod are words.

## Events — one .gml file per event in objects/<name>/

| file | runs |
|---|---|
| create.gml / destroy.gml | when the instance is made / destroyed |
| step-begin.gml, step.gml, step-end.gml | every step: first, middle, last |
| alarm-0.gml … alarm-11.gml | when alarm[n] counts down to 0 |
| keyboard-<code>.gml / keypress-<code>.gml / keyrelease-<code>.gml | a key held / pressed / released (37 left, 38 up, 39 right, 40 down, 32 space, 13 enter) |
| mouse-<n>.gml | 0–2 a button held on the instance, 4–6 pressed, 7–9 released, 3 none; 50–58 the same anywhere |
| collision-<object>.gml | touching an instance of <object> (other = it) |
| draw.gml | draws the instance itself (instead of its sprite) |
| other-0 / 2 / 3 / 4 / 5 / 6 / 7 .gml | outside the room / game start / game end / room start / room end / no more lives / animation end |
| other-10 … other-25 .gml | user events 0–15 (event_user(n)) |

The step order is GameMaker 5's: begin step, alarms, keyboard, key press, key release, mouse, step, timelines,
movement (speed, gravity), outside room, collisions, end step, animation, views.

`)
	for _, k := range []struct{ group, title string }{
		{"built-in", "Built-in functions (math, strings, random)"},
		{"game", "Game functions (instances, rooms, sound, highscores …)"},
		{"actions", "Drag-and-drop actions (the last argument is \"relative\" when the action has one)"},
		{"drawing", "Drawing (in draw events)"},
	} {
		fmt.Fprintf(w, "## %s\n\n%s\n\n", k.title, strings.Join(groups[k.group], ", "))
	}
	consts := map[string]bool{}
	for k := range gml.Constants() {
		consts[k] = true
	}
	globals := map[string]bool{}
	for k := range gml.GlobalBuiltins {
		globals[k] = true
	}
	fmt.Fprintf(w, "## Game-wide variables\n\n%s\n\n", strings.Join(sorted(globals), ", "))
	fmt.Fprintf(w, `## Instance variables

x, y, xprevious, yprevious, xstart, ystart, hspeed, vspeed, speed, direction, gravity, gravity_direction,
image_index (image_single), image_speed, sprite_index, object_index, solid, alarm[0–11], timeline_index,
timeline_position — and any variable the code sets. global.name for game-wide ones; var for a script's locals;
argument0 … argument9 in scripts.

## Constants

%s
`, strings.Join(sorted(consts), ", "))
}

func cmdReference(args []string) error {
	if len(args) == 1 {
		f, err := os.Create(args[0])
		if err != nil {
			return err
		}
		defer f.Close()
		writeReference(f)
		return nil
	}
	writeReference(os.Stdout)
	return nil
}
