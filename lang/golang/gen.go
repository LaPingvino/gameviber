package golang

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

// Generating native Go from a game's Go files: each event or script file
// becomes its own package (helper names in two files never clash), its
// function registered by the file's path in Compiled / CompiledScripts, so a
// program built from it runs the code natively — the same gv API the
// interpreter offers, the same file:line in compile errors (statement files
// are wrapped on their first line, as the interpreter wraps them).

// GvImport is the gv package's real import path.
const GvImport = "github.com/LaPingvino/gameviber/gv"

// GenFile is one game file to compile in: its path in the game folder and
// source; Script: a scripts/ file (args in, a value out) rather than an event.
type GenFile struct {
	Path, Src string
	Script    bool
}

var (
	packageClause = regexp.MustCompile(`(?m)^package\s+main\b`)
	gvImport      = regexp.MustCompile(`"gv"`)
)

// Generate is the Go source of a package per file (dir "f0", "f1" … under
// root, each with one .go file) and of a register file in package `pkg`
// (importPath: the import path of root) that puts every file's function in
// Compiled / CompiledScripts from its init. Keys of the result are paths
// relative to root.
func Generate(files []GenFile, pkg, importPath string) (map[string][]byte, error) {
	sorted := append([]GenFile(nil), files...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })
	out := map[string][]byte{}
	var reg strings.Builder
	fmt.Fprintf(&reg, "// Code generated by gameviber export; DO NOT EDIT.\n\npackage %s\n\nimport (\n\t\"github.com/LaPingvino/gameviber/lang/golang\"\n", pkg)
	var body strings.Builder
	for i, f := range sorted {
		name := fmt.Sprintf("f%d", i)
		var src string
		if strings.HasPrefix(strings.TrimSpace(stripComments(f.Src)), "package") {
			// a whole file: its own package clause and imports, "gv" pointed at
			// the real package; Event / Script are already exported names
			src = packageClause.ReplaceAllString(f.Src, "package "+name)
			src = gvImport.ReplaceAllString(src, `gv "`+GvImport+`"`)
		} else if f.Script {
			src = "package " + name + "; import gv \"" + GvImport + "\"; func Script(g *gv.Ctx, args []gv.Value) gv.Value { " + f.Src + "\nreturn gv.Value{}\n}\n"
		} else {
			src = "package " + name + "; import gv \"" + GvImport + "\"; func Event(g *gv.Ctx) { " + f.Src + "\n}\n"
		}
		out[name+"/"+name+".go"] = []byte("//line " + f.Path + ":1\n" + src)
		fmt.Fprintf(&reg, "\t%s %q\n", name, importPath+"/"+name)
		if f.Script {
			fmt.Fprintf(&body, "\tgolang.CompiledScripts[%q] = %s.Script\n", f.Path, name)
		} else {
			fmt.Fprintf(&body, "\tgolang.Compiled[%q] = %s.Event\n", f.Path, name)
		}
	}
	reg.WriteString(")\n\n// The game's Go code, compiled in.\nfunc init() {\n")
	reg.WriteString(body.String())
	reg.WriteString("}\n")
	out["register.go"] = []byte(reg.String())
	return out, nil
}
